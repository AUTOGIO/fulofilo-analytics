        - [ ] For Digital Textile Print: ICC profile required
        - [ ] For Screen Print: Color separation by channel required
        - [ ] For Sublimation: Confirm substrate compatibility with \(project.material.rawValue)

        ## Sample Approval Requirement
        > ⚠️ Physical factory sample MUST be approved before mass production.
        > Do NOT proceed to production without signed sample approval.

        ---
        *Generated by PrintFactoryKit.*
        """
    }

    private func materialSpecificNotes(project: FactoryProject) -> String {
        switch project.material {
        case .cetimColado:
            return """
            - **Material:** Cetim + Lona (impressão no cetim, colado na lona)
            - **Process:** Arte é impressa digitalmente no cetim; o cetim impresso é
              então colado sobre a lona estrutural da bolsa.
            - **Confirm with factory:**
              - [ ] Tipo de cola utilizado (PU, hot-melt, etc.)
              - [ ] Espessura do cetim e da lona
              - [ ] Resistência da colagem à água e ao uso
              - [ ] Temperatura e pressão do processo de colagem
              - [ ] Área de sangramento (bleed) necessária nas bordas
              - [ ] Comportamento das cores do cetim após colagem (possível shift)
            - **⚠️ Warning:** Impressão em cetim pode apresentar variação de cor
              diferente do monitor — amostra física obrigatória.
            """
        case .polyesterElastano:
            return """
            - **Material:** Poliéster com Elastano
            - **Process:** Impressão sublimática é o método recomendado para este material.
              O elastano permite elasticidade — ideal para cangas e peças de praia.
            - **Confirm with factory:**
              - [ ] Percentual de elastano na composição (ex: 92% PES / 8% EA)
              - [ ] Gramatura do tecido (g/m²)
              - [ ] Compatibilidade com sublimação (poliéster mínimo ~85%)
              - [ ] Encolhimento após lavagem
              - [ ] Comportamento das bordas (costura, bainha ou corte a laser)
              - [ ] Padrão de cor após sublimação — realizar teste de cor antes do bulk
            - **⚠️ Warning:** Elastano pode reduzir a intensidade das cores na sublimação.
              Ajuste de cor na arte pode ser necessário — confirmar com fábrica.
            """
        case .canvas12oz:
            return """
            - **Material:** Canvas 12 oz
            - **Process:** Impressão digital têxtil ou serigrafia conforme método selecionado.
            - **Confirm with factory:**
              - [ ] Acabamento da lona (cru, branqueado, tingido)
              - [ ] Compatibilidade com o método de impressão selecionado
              - [ ] Resistência à lavagem após impressão
            """
        case .polyester:
            return """
            - **Material:** Poliéster
            - **Process:** Sublimação ou impressão digital têxtil conforme método.
            - **Confirm with factory:**
              - [ ] Gramatura do tecido
              - [ ] Compatibilidade com método de impressão selecionado
            """
        case .cotton:
            return """
            - **Material:** Algodão (Cotton)
            - **Note:** Algodão não é compatível com sublimação. Use impressão digital
              têxtil (DTG/DTF) ou serigrafia.
            - **Confirm with factory:**
              - [ ] Fio e gramatura
              - [ ] Pré-tratamento necessário para impressão
            """
        case .other:
            return "- **Material:** Outro — confirmar especificações diretamente com a fábrica."
        }
    }

    private func techPackMaterialDetail(project: FactoryProject) -> String {
        switch project.material {
        case .cetimColado:
            return """
            - **Outer layer:** Cetim impresso digitalmente
            - **Base layer:** Lona (canvas estrutural)
            - **Bond process:** Colagem — tipo de cola a confirmar com fábrica
            - **⚠️ Process note:** Confirmar resistência da colagem, bleed nas bordas e shift de cor
            """
        case .polyesterElastano:
            return """
            - **Composition:** Poliéster + Elastano (% a confirmar com fábrica)
            - **Recommended print:** Sublimação
            - **⚠️ Process note:** Confirmar % mínimo de PES para sublimação e comportamento do elastano
            """
        case .canvas12oz:
            return "- **Weight:** 12 oz / 340 g/m² approximately"
        case .polyester, .cotton, .other:
            return ""
        }
    }

    func techPack(project: FactoryProject, analysis: ArtworkAnalysis) -> String {
        let s = project.specs
        let hasDims = s.widthCM > 0 || s.heightCM > 0
        let hasPrint = s.printAreaWidthCM > 0 || s.printAreaHeightCM > 0
        let hasZipper = !s.zipperColor.isEmpty || s.zipperLengthCM > 0
        let hasStrap = !s.strapMaterial.isEmpty || s.strapWidthCM > 0

        let dimLine     = hasDims  ? s.dimensionSummary : "⚠️ Not specified — confirm with factory"
        let printLine   = hasPrint ? s.printAreaSummary + " @ \(s.targetDPI) DPI" : "⚠️ Not specified — confirm with factory"
        let zipperLine  = hasZipper
            ? [s.zipperColor, s.zipperType, s.zipperLengthCM > 0 ? "\(s.zipperLengthCM) cm" : ""].filter { !$0.isEmpty }.joined(separator: ", ")
            : "⚠️ Not specified"
        let strapLine   = hasStrap
            ? [s.strapMaterial, s.strapWidthCM > 0 ? "W:\(s.strapWidthCM) cm" : "", s.strapLengthCM > 0 ? "L:\(s.strapLengthCM) cm" : ""].filter { !$0.isEmpty }.joined(separator: ", ")
            : "⚠️ Not specified"
        let liningLine  = s.liningColor.isEmpty ? "⚠️ Not specified" : "\(s.liningColor)\(s.liningMaterial.isEmpty ? "" : " — \(s.liningMaterial)")"
        let seamLine    = s.seam.isEmpty ? "1 cm overlock (default — confirm)" : s.seam
        let qtyLine     = s.targetQuantity > 0 ? "\(s.targetQuantity) units" : "⚠️ Not defined — confirm MOQ with factory"

        let printPx = hasPrint ? " (\(s.printPixelWidth) × \(s.printPixelHeight) px at \(s.targetDPI) DPI)" : ""

        return """
        # PRODUCT TECH PACK
        **Project:** \(project.projectCode) — \(project.displayName)
        **Collection:** \(project.displayCollectionName)
        **Product:** \(project.productType.rawValue)
        **Factory:** \(project.factoryName.isEmpty ? "Not specified" : project.displayFactoryName)

        ---

        ## Product Specifications

        ### Material
        - **Primary Material:** \(project.material.rawValue)
        \(techPackMaterialDetail(project: project))
        - **Lining:** \(liningLine)

        ### Dimensions
        - **Overall:** \(dimLine)
        - **Print Area:** \(printLine)\(printPx)
        - **Seam Allowance:** \(seamLine)

        ### Print Specifications
        - **Print Method:** \(project.printMethod.rawValue)
        - **Artwork Source:** \(analysis.fileFormat) — \(analysis.pixelWidth) × \(analysis.pixelHeight) px (original)
        - **Repeat Tiles Included:** seamless_2x2.png, seamless_3x3.png, sparse_2x2.png
        - **Print-scaled File Included:** artwork_print_scaled.png\(printPx)

        ### Hardware & Trims
        - **Zipper:** \(zipperLine)
        - **Straps/Handles:** \(strapLine)
        - **Label:** Inner label — brand / care instructions (client to provide artwork)
        - **Hangtag:** Optional — client to confirm

        ### Construction
        - **Closure:** Zipper
        - **Seam Finish:** \(seamLine)
        - **Reinforcement:** Bar tacks at strap attachment points

        ### Order Information
        - **Target Quantity:** \(qtyLine)

        ### Factory Confirmation Required
        1. Confirm MOQ and unit price for quantity above
        2. Confirm lead time from sample approval to delivery
        3. Confirm acceptable color variation tolerance (±__%)
        4. Confirm required artwork file format for your RIP software
        5. Confirm pre-production sample will be provided before bulk run

        ---
        *Generated by PrintFactoryKit — \(hasDims && hasPrint ? "Specifications provided by client." : "⚠️ Some fields incomplete — see items marked above.")*
        """
    }

