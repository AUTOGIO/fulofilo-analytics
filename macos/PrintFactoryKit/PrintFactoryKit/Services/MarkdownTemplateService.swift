        - **Format:** \(analysis.fileFormat)
        - **Dimensions:** \(analysis.pixelWidth) × \(analysis.pixelHeight) px
        - **File Size:** \(analysis.fileSizeFormatted)
        - **Resolution Note:** \(resNote)
        - **Source Type:** Raster/Bitmap (not vector)

        ## Material & Process Notes
        \(materialNotes)

        ## Required Preparation Before Factory Production

        ### 1. Vectorization
        - [ ] Convert artwork to vector format (AI, EPS, or SVG)
        - [ ] Minimum recommended: 300 DPI equivalent at print dimensions
