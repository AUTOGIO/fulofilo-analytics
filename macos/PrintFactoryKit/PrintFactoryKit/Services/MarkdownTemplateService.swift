import Foundation

final class MarkdownTemplateService {

    static let shared = MarkdownTemplateService()
    private init() {}

    func designBrief(project: FactoryProject, analysis: ArtworkAnalysis) -> String {
        let dateStr = DateFormatter.localizedString(from: project.createdAt, dateStyle: .long, timeStyle: .none)
        let colors = analysis.dominantColors.map { "  - \($0.hex)  (R:\($0.r) G:\($0.g) B:\($0.b))" }.joined(separator: "\n")
        return """
        # DESIGN BRIEF
        **Project Code:** \(project.projectCode)
        **Project Name:** \(project.displayName)
        **Collection:** \(project.displayCollectionName)
        **Date:** \(dateStr)
        **Factory:** \(project.factoryName.isEmpty ? "Not specified" : project.displayFactoryName)

        ---

        ## Product Information
        - **Product Type:** \(project.productType.rawValue)
        - **Material:** \(project.material.rawValue)
        - **Print Method:** \(project.printMethod.rawValue)

        ## Visual Description
        *[Describe the visual concept, motifs, and mood of the artwork here.]*

        - **Motifs:** To be described based on artwork
        - **Color Mood:** Extracted palette below
        - **Artwork Style:** Bitmap / Raster — requires vectorization

        ## Extracted Color Palette
        \(colors.isEmpty ? "  - No colors extracted" : colors)

        > ⚠️ Factory must confirm final colors using physical sample or Pantone/CMYK references.

        ## Notes
        \(project.notes.isEmpty ? "No additional notes." : project.notes)

        ---
        *Generated by PrintFactoryKit — For factory review only.*
        """
    }

    func colorPalette(project: FactoryProject, analysis: ArtworkAnalysis) -> String {
        let rows = analysis.dominantColors.enumerated().map { i, c in
            "| \(i + 1) | \(c.hex) | R:\(c.r) G:\(c.g) B:\(c.b) | Pantone TBD | CMYK TBD |"
        }.joined(separator: "\n")
        return """
        # COLOR PALETTE
        **Project:** \(project.projectCode) — \(project.displayName)

        | # | HEX | RGB | Pantone (required) | CMYK (required) |
        |---|-----|-----|--------------------|-----------------|
        \(rows.isEmpty ? "| — | No colors extracted | — | — | — |" : rows)

        ---

        ## Important Notice
        > These colors are algorithmically extracted from the raster source image.
        > They are approximate values for reference only.
        >
        > **Factory must confirm all final colors using:**
        > - Physical print sample
        > - Pantone Textile/Coated swatch confirmation
        > - CMYK profile matching appropriate for the chosen print method
        >
        > Color variation of ±5–10% is expected between digital preview and physical print.

        ---
        *Generated by PrintFactoryKit — Color values are approximate.*
        """
    }

